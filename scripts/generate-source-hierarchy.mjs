import { readdir, stat, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourceRoot = join(projectRoot, 'src')
const outputPath = join(sourceRoot, 'generated', 'currentSourcePaths.ts')
const supportedExtensions = new Set(['.ts', '.tsx', '.css'])

async function collectPaths(directory) {
  const entries = await readdir(directory)
  const paths = []

  for (const entry of entries) {
    const fullPath = join(directory, entry)
    const info = await stat(fullPath)
    if (info.isDirectory()) {
      paths.push(...await collectPaths(fullPath))
      continue
    }

    const extension = entry.slice(entry.lastIndexOf('.'))
    const pathFromSource = relative(sourceRoot, fullPath).replaceAll('\\', '/')
    if (supportedExtensions.has(extension) && pathFromSource !== 'generated/currentSourcePaths.ts') {
      paths.push(`src/${pathFromSource}`)
    }
  }

  return paths
}

const sourcePaths = (await collectPaths(sourceRoot)).sort((left, right) => left.localeCompare(right))
const generatedModule = `/**\n * Generated by scripts/generate-source-hierarchy.mjs.\n * This is a path manifest, not source-code content.\n */\nexport const CURRENT_SOURCE_PATHS = ${JSON.stringify(sourcePaths, null, 2)} as const\n`

await writeFile(outputPath, generatedModule)
